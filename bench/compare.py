#!/usr/bin/env python3
"""Benchmark table, baseline check and README section for bench_suite results (P3.6).

    compare.py RUN.json [RUN.json ...]            table (best value of each scenario over the runs)
        --baseline bench/baseline.json           fail (exit 1) on a regression of more than --tolerance
        --tolerance 0.15
        --save-baseline bench/baseline.json      store these results as the new baseline
        --readme README.md                       rewrite the section between the bench markers

Machines differ, so the check does not compare absolute numbers: for every scenario that also ran on
SQLite it compares SegVault / SQLite measured in the same run with the same ratio in the baseline. A
scenario without a SQLite value (PDO over the MySQL protocol) is compared in absolute terms and only
warns. Only the standard library is used.
"""
import json
import sys

START = "<!-- bench:start (generated by bench/compare.py: do not edit by hand) -->"
END = "<!-- bench:end -->"


def load_runs(paths):
    merged, meta = {}, None
    for p in paths:
        with open(p) as f:
            run = json.load(f)
        meta = meta or run
        for s in run["scenarios"]:
            m = merged.setdefault(s["name"], {"name": s["name"], "unit": s["unit"], "what": s["what"]})
            for k in ("segvault", "sqlite", "mariadb"):
                if k in s:
                    m[k] = max(m.get(k, 0.0), s[k])   # higher is better: the best of the runs
    order = [s["name"] for s in meta["scenarios"]]
    return meta, [merged[n] for n in order]


def fmt(v):
    if v is None:
        return "n/a"
    if v >= 100000:
        return f"{v / 1000:,.0f} k"
    if v >= 1000:
        return f"{v / 1000:,.1f} k"
    return f"{v:,.1f}"


def table(meta, rows):
    out = [f"SegVault {meta['segvault']} · SQLite {meta['sqlite']} (in-process, WAL) · MariaDB: not run "
           f"· {meta['cpus']} CPUs · scale {meta['scale']}", "",
           "| Scenario | What is measured | Unit | SegVault | SQLite | SegVault / SQLite |",
           "|---|---|---|---:|---:|---:|"]
    for r in rows:
        sv, lt = r.get("segvault"), r.get("sqlite")
        ratio = (f"{sv / lt:.3f}×" if sv / lt < 0.1 else f"{sv / lt:.2f}×") if sv and lt else "—"
        out.append(f"| `{r['name']}` | {r['what']} | {r['unit']} | {fmt(sv)} | {fmt(lt)} | {ratio} |")
    return "\n".join(out)


def check(rows, base_rows, tol):
    base = {r["name"]: r for r in base_rows}
    bad, notes = [], []
    for r in rows:
        b = base.get(r["name"])
        if not b or not r.get("segvault") or not b.get("segvault"):
            continue
        if r.get("sqlite") and b.get("sqlite"):
            now, then = r["segvault"] / r["sqlite"], b["segvault"] / b["sqlite"]
            change = now / then - 1
            line = f"{r['name']}: SegVault/SQLite {then:.3f} -> {now:.3f} ({change:+.0%})"
            (bad if change < -tol else notes).append(line)
        else:
            change = r["segvault"] / b["segvault"] - 1
            notes.append(f"{r['name']}: {fmt(b['segvault'])} -> {fmt(r['segvault'])} {r['unit']} ({change:+.0%}, absolute: not gated)")
    return bad, notes


def main(argv):
    runs, opts, i = [], {}, 0
    while i < len(argv):
        a = argv[i]
        if a in ("--baseline", "--tolerance", "--save-baseline", "--readme"):
            opts[a] = argv[i + 1]
            i += 2
        else:
            runs.append(a)
            i += 1
    if not runs:
        print(__doc__)
        return 2
    meta, rows = load_runs(runs)
    text = table(meta, rows)
    print(text)
    rc = 0
    if "--baseline" in opts:
        with open(opts["--baseline"]) as f:
            base = json.load(f)
        tol = float(opts.get("--tolerance", 0.15))
        bad, notes = check(rows, base["scenarios"], tol)
        print()
        for n in notes:
            print("  ok  ", n)
        for b in bad:
            print("  SLOW", b)
        if bad:
            print(f"\n{len(bad)} scenario(s) slower than the baseline by more than {tol:.0%} (relative to SQLite)")
            rc = 1
        else:
            print(f"\nno regression beyond {tol:.0%} against the baseline")
    if "--save-baseline" in opts:
        out = dict(meta)
        out["scenarios"] = rows
        with open(opts["--save-baseline"], "w") as f:
            json.dump(out, f, indent=2)
            f.write("\n")
    if "--readme" in opts:
        path = opts["--readme"]
        with open(path) as f:
            doc = f.read()
        a, b = doc.find(START), doc.find(END)
        if a < 0 or b < a:
            print(f"{path}: bench markers not found", file=sys.stderr)
            return 1
        doc = doc[:a + len(START)] + "\n" + text + "\n" + doc[b:]
        with open(path, "w") as f:
            f.write(doc)
    return rc


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
